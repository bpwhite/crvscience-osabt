/// Concrete cleavage event mapped onto a plasmid record.
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct CutSite {
    pub enzyme_name: String,
    pub recognition_start_0: usize,
    pub strand: Strand,
    pub cut_top_0: usize,
    pub cut_bottom_0: usize,
    pub overhang: OverhangKind,
}

/// Linear DNA fragment produced after endonuclease digestion.
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct DigestFragment {
    pub index: usize,
    pub length_bp: usize,
    pub start_0: usize,
    pub end_0: usize,
    pub left_enzyme: String,
    pub right_enzyme: String,
}

/// Supported Type IIS Golden Gate assembly enzymes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub enum GoldenGateEnzyme {
    BsaI,
    BsmBI,
    BbsI,
    SapI,
}

impl GoldenGateEnzyme {
    pub fn spec(self) -> (&'static str, &'static str, &'static str, usize) {
        // (name, recognition_5to3, spacer_nt, overhang_len)
        match self {
            Self::BsaI => ("BsaI", "GGTCTC", "A", 4),
            Self::BsmBI => ("BsmBI", "CGTCTC", "A", 4),
            Self::BbsI => ("BbsI", "GAAGAC", "AA", 4),
            Self::SapI => ("SapI", "GCTCTTC", "A", 3),
        }
    }
}

/// Silent synonymous mutation recommendation that removes an internal illegal Type IIS site inside a CDS.
