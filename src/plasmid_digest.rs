/// Terminal cohesive or blunt overhang generated by endonuclease cleavage.
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub enum OverhangKind {
    FivePrime(String),
    ThreePrime(String),
    Blunt,
}

/// Restriction endonuclease recognition and cleavage specification.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RestrictionEnzyme {
    pub name: &'static str,
    /// `5' -> 3'` IUPAC recognition motif.
    pub recognition: &'static str,
    /// Cleavage offset on the top strand relative to index `0` of `recognition`.
    pub cut_top: isize,
    /// Cleavage offset on the bottom strand (measured from index `0` of `recognition` on top strand).
    pub cut_bottom: isize,
    pub is_type_iis: bool,
    pub dam_sensitive: bool,
    pub dcm_sensitive: bool,
}

