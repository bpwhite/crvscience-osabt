/// Single scarless Type IIS Golden Gate junction with 4-bp overhang and flanked primers.
#[derive(Debug, Clone, PartialEq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct GoldenGateJunction {
    pub junction_index: usize,
    pub upstream_fragment: String,
    pub downstream_fragment: String,
    pub overhang_seq: String,
    pub downstream_fwd_primer: String,
    pub upstream_rev_primer: String,
    pub fwd_core_tm_c: f64,
    pub rev_core_tm_c: f64,
}

/// Complete Type IIS Golden Gate multi-part design report.
#[derive(Debug, Clone, PartialEq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct GoldenGatePlan {
    pub enzyme: GoldenGateEnzyme,
    pub circular: bool,
    pub estimated_set_fidelity_pct: f64,
    pub internal_illegal_sites: usize,
    pub domestication_edits: Vec<DomesticationEdit>,
    pub junctions: Vec<GoldenGateJunction>,
    pub assembled_sequence: String,
}

impl GoldenGatePlan {
    pub fn to_order_tsv(&self) -> String {
        let mut out = String::from("Name\tSequence\tLength_nt\tCore_Tm_C\tFusion_Overhang\n");
        for j in &self.junctions {
            out.push_str(&format!(
                "GG_J{}_{}_F\t{}\t{}\t{:.1}\t{}\n",
                j.junction_index + 1,
                j.downstream_fragment,
                j.downstream_fwd_primer,
                j.downstream_fwd_primer.len(),
                j.fwd_core_tm_c,
                j.overhang_seq
            ));
            out.push_str(&format!(
                "GG_J{}_{}_R\t{}\t{}\t{:.1}\t{}\n",
                j.junction_index + 1,
                j.upstream_fragment,
                j.upstream_rev_primer,
                j.upstream_rev_primer.len(),
                j.rev_core_tm_c,
                j.overhang_seq
            ));
        }
        out
    }
}

#[inline]
fn wrap_idx(pos: isize, n: usize) -> usize {
    pos.rem_euclid(n as isize) as usize
}

/// Scans `rec` for recognition and cleavage sites across `enzyme_filter` (`None` = entire catalog).
pub fn find_cut_sites(rec: &PlasmidRecord, enzyme_filter: Option<&[String]>) -> Vec<CutSite> {
    let n = rec.sequence.len();
    if n < 4 {
        return Vec::new();
    }
    let pad = if rec.circular { 24.min(n) } else { 0 };
    let track = format!("{}{}", rec.sequence, &rec.sequence[..pad]);
    let tb = track.as_bytes();

    let mut sites = Vec::new();
    for enz in ENZYME_CATALOG {
        if let Some(names) = enzyme_filter {
            if !names.iter().any(|q| q.eq_ignore_ascii_case(enz.name)) {
                continue;
            }
        }
        let motif_f = enz.recognition.as_bytes();
        let motif_rc_str = reverse_complement(enz.recognition);
        let motif_r = motif_rc_str.as_bytes();
        let mlen = motif_f.len();
        let palindromic = motif_f == motif_r;
        let max_start = if rec.circular { n } else { n.saturating_sub(mlen) + 1 };

        for pos in 0..max_start {
            if pos + mlen > tb.len() {
                break;
            }
            let win = &tb[pos..(pos + mlen)];
            if win == motif_f {
                let c_top = pos as isize + enz.cut_top;
                let c_bot = pos as isize + enz.cut_bottom;
                if !rec.circular && (c_top < 0 || c_bot < 0 || c_top > n as isize || c_bot > n as isize) {
                    continue;
                }
                let overhang = extract_overhang(&rec.sequence, c_top, c_bot);
                sites.push(CutSite {
                    enzyme_name: enz.name.to_string(),
                    recognition_start_0: pos,
                    strand: Strand::Forward,
                    cut_top_0: wrap_idx(c_top, n),
                    cut_bottom_0: wrap_idx(c_bot, n),
                    overhang,
                });
            }
            if !palindromic && win == motif_r {
                // Non-palindromic Type IIS site on reverse strand cuts upstream of motif (`pos + mlen - cut_bottom`)
                let c_top = (pos + mlen) as isize - enz.cut_bottom;
                let c_bot = (pos + mlen) as isize - enz.cut_top;
                if !rec.circular && (c_top < 0 || c_bot < 0 || c_top > n as isize || c_bot > n as isize) {
                    continue;
                }
                let overhang = extract_overhang(&rec.sequence, c_top, c_bot);
                sites.push(CutSite {
                    enzyme_name: enz.name.to_string(),
                    recognition_start_0: pos,
                    strand: Strand::Reverse,
                    cut_top_0: wrap_idx(c_top, n),
                    cut_bottom_0: wrap_idx(c_bot, n),
                    overhang,
                });
            }
        }
    }

    sites.sort_by_key(|s| s.cut_top_0);
    sites
}

fn extract_overhang(seq: &str, c_top: isize, c_bot: isize) -> OverhangKind {
    let n = seq.len();
    let b = seq.as_bytes();
    if c_top == c_bot {
        OverhangKind::Blunt
    } else if c_top < c_bot {
        let mut s = String::new();
        for p in c_top..c_bot {
            s.push(b[wrap_idx(p, n)] as char);
        }
        OverhangKind::FivePrime(s)
    } else {
        let mut s = String::new();
        for p in c_bot..c_top {
            s.push(complement_base(b[wrap_idx(p, n)]) as char);
        }
        OverhangKind::ThreePrime(s)
    }
}

/// Returns only unique (single-site) restriction cutters across `rec`—ideal for vector map labels.
pub fn find_unique_cutters(rec: &PlasmidRecord) -> Vec<CutSite> {
    let all = find_cut_sites(rec, None);
    let mut uniques = Vec::new();
    for s in &all {
        let count = all
            .iter()
            .filter(|x| x.enzyme_name == s.enzyme_name)
            .count();
        if count == 1 {
            uniques.push(s.clone());
        }
    }
    uniques
}

/// Simulates complete restriction digestion of `rec` by `enzyme_names`, returning fragments sorted
/// from largest to smallest (`bp`) as resolved on an agarose gel.
pub fn simulate_restriction_digest(
    rec: &PlasmidRecord,
    enzyme_names: &[String],
) -> Result<Vec<DigestFragment>, OligoError> {
    let n = rec.sequence.len();
    if n == 0 {
        return Err(OligoError::EmptySequence);
    }
    let mut cuts = find_cut_sites(rec, Some(enzyme_names));
    cuts.sort_by_key(|c| c.cut_top_0);
    cuts.dedup_by_key(|c| c.cut_top_0);

    if cuts.is_empty() {
        return Ok(vec![DigestFragment {
            index: 1,
            length_bp: n,
            start_0: 0,
            end_0: n - 1,
            left_enzyme: if rec.circular {
                "Uncut (Supercoiled/Nicked)".to_string()
            } else {
                "5'-Terminus".to_string()
            },
            right_enzyme: if rec.circular {
                "Uncut".to_string()
            } else {
                "3'-Terminus".to_string()
            },
        }]);
    }

    let mut frags = Vec::new();
    if rec.circular {
        for i in 0..cuts.len() {
            let cur = &cuts[i];
            let nxt = &cuts[(i + 1) % cuts.len()];
            let len = if nxt.cut_top_0 > cur.cut_top_0 {
                nxt.cut_top_0 - cur.cut_top_0
            } else {
                (n - cur.cut_top_0) + nxt.cut_top_0
            };
            frags.push(DigestFragment {
                index: i + 1,
                length_bp: len,
                start_0: cur.cut_top_0,
                end_0: wrap_idx(nxt.cut_top_0 as isize - 1, n),
                left_enzyme: cur.enzyme_name.clone(),
                right_enzyme: nxt.enzyme_name.clone(),
            });
        }
    } else {
        let mut prev_pos = 0usize;
        let mut prev_name = String::from("5'-End");
        for c in &cuts {
            if c.cut_top_0 > prev_pos {
                frags.push(DigestFragment {
                    index: frags.len() + 1,
                    length_bp: c.cut_top_0 - prev_pos,
                    start_0: prev_pos,
                    end_0: c.cut_top_0 - 1,
                    left_enzyme: prev_name.clone(),
                    right_enzyme: c.enzyme_name.clone(),
                });
            }
            prev_pos = c.cut_top_0;
            prev_name = c.enzyme_name.clone();
        }
        if prev_pos < n {
            frags.push(DigestFragment {
                index: frags.len() + 1,
                length_bp: n - prev_pos,
                start_0: prev_pos,
                end_0: n - 1,
                left_enzyme: prev_name,
                right_enzyme: "3'-End".to_string(),
            });
        }
    }

    frags.sort_by(|a, b| b.length_bp.cmp(&a.length_bp));
    for (idx, f) in frags.iter_mut().enumerate() {
        f.index = idx + 1;
    }
    Ok(frags)
}

/// Evaluates predicted T4 DNA ligase multi-junction overhang fidelity (`0.0..=100.0%`) modeled on
/// Potapov et al. (2018, *ACS Synth. Biol.* 7:2665) rules: penalizes palindromic self-ligation,
/// duplicate/reverse-complement cross-junction collisions, 3-of-4 base near-cognate mismatches
/// (especially G·T wobble), homopolymers (`AAAA`/`GGGG`), and extreme GC%.
pub fn score_overhang_set_fidelity(overhangs: &[String]) -> f64 {
    if overhangs.is_empty() {
        return 100.0;
    }
    let mut fidelity = 99.6_f64;

    for (i, oh) in overhangs.iter().enumerate() {
        let rc = reverse_complement(oh);
        // Self-complementary palindrome (e.g., AATT, GATC) ligates to itself, causing ~50%+ failure
        if *oh == rc {
            fidelity -= 45.0;
        }
        // Homopolymer 4-mer has low T4 ligase efficiency & high slippage
        if oh.bytes().all(|b| b == oh.as_bytes()[0]) {
            fidelity -= 18.0;
        }
        let gc = oh.bytes().filter(|b| matches!(b, b'G' | b'C')).count();
        if gc == 0 || gc == oh.len() {
            fidelity -= 3.5;
        }

        for other in overhangs.iter().skip(i + 1) {
            let other_rc = reverse_complement(other);
            if *oh == *other || *oh == other_rc {
                fidelity -= 55.0; // Direct cross-junction collision
            } else if oh.len() == other.len() {
                // Count Watson-Crick matches between `oh` (5'->3') and `other` (5'->3' antiparallel = compare to `other_rc`)
                let matches_rc = oh
                    .bytes()
                    .zip(other_rc.bytes())
                    .filter(|(a, b)| a == b)
                    .count();
                let matches_same = oh
                    .bytes()
                    .zip(other.bytes())
                    .filter(|(a, b)| a == b)
                    .count();
                if matches_rc >= oh.len() - 1 || matches_same >= oh.len() - 1 {
                    fidelity -= 8.5; // 3-of-4 near-cognate misligation risk
                }
            }
        }
    }

    (fidelity.clamp(1.0, 99.8) * 10.0).round() / 10.0
}

fn suggest_silent_domestication(
    frag_name: &str,
    seq: &str,
    motif: &str,
) -> Vec<DomesticationEdit> {
    let rc_motif = reverse_complement(motif);
    let mlen = motif.len();
    let mut edits = Vec::new();
    let synonyms: &[(&str, &str)] = &[
        ("GGT", "GGC"), ("GGC", "GGT"), ("GGA", "GGC"), ("GGG", "GGC"),
        ("CTC", "CTG"), ("CTT", "CTG"), ("CTA", "CTG"), ("CTG", "CTC"),
        ("CGT", "CGC"), ("CGC", "CGT"), ("CGA", "CGC"), ("CGG", "CGC"),
        ("AGA", "CGC"), ("AGG", "CGC"),
        ("GAA", "GAG"), ("GAG", "GAA"),
        ("GAC", "GAT"), ("GAT", "GAC"),
        ("TCT", "TCC"), ("TCC", "TCT"), ("TCA", "TCC"), ("TCG", "TCC"),
    ];

    for pos in 0..=seq.len().saturating_sub(mlen) {
        let win = &seq[pos..(pos + mlen)];
        if win != motif && win != rc_motif {
            continue;
        }
        // Check frame-0 codons overlapping `pos .. pos + mlen`
        let first_codon = (pos / 3) * 3;
        let mut found = false;
        let mut c_start = first_codon;
        while c_start + 3 <= seq.len() && c_start < pos + mlen && !found {
            let orig_codon = &seq[c_start..(c_start + 3)];
            let aa = translate_dna(orig_codon).chars().next().unwrap_or('X');
            for &(from_c, to_c) in synonyms {
                if orig_codon == from_c {
                    let mut mutated = seq.to_string();
                    mutated.replace_range(c_start..(c_start + 3), to_c);
                    let check_start = pos.saturating_sub(mlen);
                    let check_end = (pos + 2 * mlen).min(mutated.len());
                    let region = &mutated[check_start..check_end];
                    if !region.contains(motif) && !region.contains(&rc_motif) {
                        edits.push(DomesticationEdit {
                            fragment_name: frag_name.to_string(),
                            site_pos_0: pos,
                            codon_start_0: c_start,
                            original_codon: orig_codon.to_string(),
                            silent_codon: to_c.to_string(),
                            amino_acid: aa,
                        });
                        found = true;
                        break;
                    }
                }
            }
            c_start += 3;
        }
    }
    edits
}

/// Designs a scarless Type IIS Golden Gate assembly across ordered `(name, sequence)` fragments,
/// auditing internal illegal recognition sites (with silent codon domestication fixes) and generating
/// flanked Type IIS PCR primers (`5'-AAAA-[motif]-[spacer]-[overhang_core]-3'`).
pub fn design_goldengate_assembly(
    raw_fragments: &[(String, String)],
    enzyme: GoldenGateEnzyme,
    circular: bool,
) -> Result<GoldenGatePlan, OligoError> {
    let min_f = if circular { 1 } else { 2 };
    if raw_fragments.len() < min_f {
        return Err(OligoError::AssemblyDesignFailed {
            junction_index: 0,
            reason: format!("Golden Gate requires >= {min_f} fragment(s)."),
        });
    }

    let (_, motif, spacer, oh_len) = enzyme.spec();
    let rc_motif = reverse_complement(motif);
    let cond = ReactionConditions::for_preset(PolymerasePreset::Q5);

    let mut frags = Vec::with_capacity(raw_fragments.len());
    let mut illegal_count = 0usize;
    let mut domestications = Vec::new();

    for (idx, (name, raw_s)) in raw_fragments.iter().enumerate() {
        let seq = normalize_dna(raw_s)?;
        if seq.len() < 40 {
            return Err(OligoError::AssemblyDesignFailed {
                junction_index: idx,
                reason: format!("Fragment '{name}' ({} bp) must be >= 40 bp.", seq.len()),
            });
        }
        illegal_count += seq.matches(motif).count() + seq.matches(&rc_motif).count();
        domestications.extend(suggest_silent_domestication(name, &seq, motif));
        frags.push((name.clone(), seq));
    }

    let n = frags.len();
    let n_junc = if circular { n } else { n - 1 };
    let mut overhangs = Vec::with_capacity(n_junc);
    let mut junctions = Vec::with_capacity(n_junc);

    // High-fidelity Potapov-validated non-palindromic fallback fusion overhangs when boundary bases collide
    let hf_fallbacks = [
        "AATG", "AGGT", "GCTT", "CGCT", "GGTA", "ACTA", "TTCG", "CAGA", "TACA", "CCGA", "GTCA",
        "ATGA",
    ];

    for j in 0..n_junc {
        let up_i = j;
        let dn_i = (j + 1) % n;
        let (up_name, up_seq) = &frags[up_i];
        let (dn_name, dn_seq) = &frags[dn_i];

        // Scarless fusion uses the first `oh_len` bases of the downstream fragment as the sticky overhang;
        // if that collides with an earlier overhang or is palindromic, substitute from Potapov HF set.
        let natural_oh = dn_seq[..oh_len].to_string();
        let mut test_set = overhangs.clone();
        test_set.push(natural_oh.clone());
        let chosen_oh = if score_overhang_set_fidelity(&test_set) >= 85.0 {
            natural_oh.clone()
        } else {
            hf_fallbacks
                .iter()
                .map(|s| s[..oh_len.min(s.len())].to_string())
                .find(|cand| {
                    let mut trial = overhangs.clone();
                    trial.push(cand.clone());
                    score_overhang_set_fidelity(&trial) >= 85.0
                })
                .unwrap_or(natural_oh.clone())
        };
        overhangs.push(chosen_oh.clone());

        // Pick 3' template-annealing cores targeting ~60 C
        let mut f_core_len = 18usize;
        let mut f_tm = 0.0;
        for l in 18..=28.min(dn_seq.len()) {
            let t = calc_perfect_duplex(&dn_seq[..l], &cond, 60.0)?.tm_salt_corrected_c;
            f_core_len = l;
            f_tm = t;
            if t >= 59.5 {
                break;
            }
        }
        let dn_core = &dn_seq[..f_core_len];
        let fwd_primer = if chosen_oh == natural_oh {
            // `chosen_oh` is already the 5' start of `dn_core`!
            format!("AAAA{motif}{spacer}{dn_core}")
        } else {
            format!("AAAA{motif}{spacer}{chosen_oh}{dn_core}")
        };

        let up_rc = reverse_complement(up_seq);
        let mut r_core_len = 18usize;
        let mut r_tm = 0.0;
        for l in 18..=28.min(up_rc.len()) {
            let t = calc_perfect_duplex(&up_rc[..l], &cond, 60.0)?.tm_salt_corrected_c;
            r_core_len = l;
            r_tm = t;
            if t >= 59.5 {
                break;
            }
        }
        let up_core_rc = &up_rc[..r_core_len];
        let rc_oh = reverse_complement(&chosen_oh);
        let rev_primer = format!("AAAA{motif}{spacer}{rc_oh}{up_core_rc}");

        junctions.push(GoldenGateJunction {
            junction_index: j,
            upstream_fragment: up_name.clone(),
            downstream_fragment: dn_name.clone(),
            overhang_seq: chosen_oh,
            downstream_fwd_primer: fwd_primer,
            upstream_rev_primer: rev_primer,
            fwd_core_tm_c: (f_tm * 10.0).round() / 10.0,
            rev_core_tm_c: (r_tm * 10.0).round() / 10.0,
        });
    }

    let fidelity = score_overhang_set_fidelity(&overhangs);
    let assembled: String = frags.iter().map(|(_, s)| s.as_str()).collect();

    Ok(GoldenGatePlan {
        enzyme,
        circular,
        estimated_set_fidelity_pct: fidelity,
        internal_illegal_sites: illegal_count,
        domestication_edits: domestications,
        junctions,
        assembled_sequence: assembled,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn digests_demo_plasmid_and_domesticates_internal_bsai_site() {
        let rec = PlasmidRecord::demo_pcrv_gfp();
        let uniques = find_unique_cutters(&rec);
        assert!(uniques.iter().any(|u| u.enzyme_name == "EcoRI"));
        assert!(uniques.iter().any(|u| u.enzyme_name == "XhoI"));

        let frags = simulate_restriction_digest(
            &rec,
            &["EcoRI".to_string(), "XhoI".to_string()],
        )
        .unwrap();
        assert_eq!(frags.len(), 2);
        assert_eq!(frags[0].length_bp + frags[1].length_bp, rec.sequence.len());

        // CDS containing internal BsaI site `GGTCTC` (Gly-Leu: GGT CTC) -> silent GGC CTC domestication
        let part1 = "ATGGGCTAGCTAGCGATCGATCGTAGGTCTCGCTAGCTAGCGATCGATCGTAGCTAGCTAGCGATCGAT";
        let part2 = "AATGAAAGGGCCCTTTAAAGCTAGCTAGCGATCGATCGTAGCTAGCTAGCGATCGATCGTAGCTAGCTA";
        let gg = design_goldengate_assembly(
            &[
                ("Part1_InternalBsaI".to_string(), part1.to_string()),
                ("Part2_Clean".to_string(), part2.to_string()),
            ],
            GoldenGateEnzyme::BsaI,
            true,
        )
        .unwrap();
        assert_eq!(gg.internal_illegal_sites, 1);
        assert!(!gg.domestication_edits.is_empty());
        assert!(gg.estimated_set_fidelity_pct >= 85.0);
    }
}
